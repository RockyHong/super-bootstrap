#!/usr/bin/env bash
# Assemble the doc-sync probe prompts from the scanner text and diff/. Zero LLM calls.
#
# Four prompts: {red,green} x {case-a,case-c}. Within one case, red and green share
# the framing, the scope block, the diff and the task line byte for byte; the only
# difference is the scanner text. RED is the agent body at RED_REV (before the
# restatement step); GREEN is the working-tree agent body plus the restatement
# predicate. Re-run after any edit to either file, before a probe round.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$HERE" rev-parse --show-toplevel)"
AGENT=plugins/super-bootstrap/agents/doc-sync-scan.md
PRED=plugins/super-bootstrap/skills/commit/assets/restatement-predicate.md
RED_REV=f65760c
TODAY=2026-10-27

body() {   # strip leading frontmatter
  awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm'
}

framing() {   # framing <case>
  cat <<EOF
You are the doc-sync judge for one commit in a small project. The procedure you run
is the agent text in the fenced block below; follow it exactly.

## Where things are

Treat \`bench/restatement-axis/fixture/\` as the repository root: every path below and
every path the docs cite resolves relative to it. The project's doc surface is exactly
these six files:

- \`README.md\`
- \`docs/overview.md\`
- \`docs/operations.md\`
- \`docs/sensors.md\`
- \`docs/door-interlock.md\`
- \`docs/recipes.md\`

Read, grep, or glob these six files and nothing else. Do **not** open
\`bench/restatement-axis/fixture/ANSWER-KEY.md\`, any other file under
\`bench/restatement-axis/\`, or anything elsewhere in the repository. Anything else
you open invalidates the run. The project has no \`CLAUDE.md\`, so step 1 takes its
default surface, which is the six files above.

The files on disk are the **pre-image**: the diff below is not applied to them. Judge
as if the diff has landed — each changed line reads as its \`+\` side.

Do not write any file. Return your output as your reply.

EOF
}

scanner_red() {
  printf '## The agent text\n\n````markdown\n'
  git -C "$ROOT" show "$RED_REV:$AGENT" | body
  printf '````\n\n'
}

scanner_green() {
  printf '## The agent text\n\n````markdown\n'
  body < "$ROOT/$AGENT"
  printf '````\n\n'
  printf '## The restatement predicate\n\nStep 6 cites the restatement predicate by path. Its full text is this block; do not\nopen it from disk.\n\n````markdown\n'
  cat "$ROOT/$PRED"
  printf '````\n\n'
}

scope() {   # scope <case>
  printf 'Today'"'"'s date: %s.\n\n## Scan scope\n\n' "$TODAY"
  case "$1" in
    case-a)
      cat <<'EOF'
- `README.md`

How the gate produced it (mechanical, no judgment):

- **Grep lane** — `doc-links.sh terms` on `README.md` printed nothing (generic basename); the lane is empty.
- **Citer lane** — the changed hunk resolves to anchor `#how-it-works` on `README.md`; `doc-links.sh refs` on it returned nothing.
- **Self lane** — `README.md` is a changed doc-surface file; it joins the scope.
- **Link-target lane** — the diff adds no link.
- Scope = 1 doc, under the 8-doc ceiling.
EOF
      ;;
    case-c)
      cat <<'EOF'
- `docs/door-interlock.md`
- `README.md`
- `docs/overview.md`
- `docs/operations.md`

How the gate produced it (mechanical, no judgment):

- **Grep lane** — `doc-links.sh terms` on `docs/door-interlock.md` printed `door-interlock`; `doc-links.sh hits` returned `README.md`, `docs/operations.md`, `docs/overview.md`.
- **Citer lane** — the changed hunk resolves to anchor `#interlock-rule` on `docs/door-interlock.md`; `doc-links.sh refs` on it returned `README.md`, `docs/operations.md`, `docs/overview.md`.
- **Self lane** — `docs/door-interlock.md` is a changed doc-surface file; it joins the scope.
- **Link-target lane** — the diff adds no link.
- Scope = 4 docs, under the 8-doc ceiling.
EOF
      ;;
  esac
  printf '\n'
}

diffblock() {   # diffblock <case>
  printf '## The diff\n\n```diff\n'
  cat "$HERE/diff/$1.diff"
  printf '```\n\n'
}

task() {
  cat <<'EOF'
## Your job

Run the agent text's § Scan over the scope above against this diff, and return the
output its § Output contract defines.
EOF
}

header() {   # header <arm> <case>
  cat <<EOF
# Probe prompt — restatement axis, doc-sync $1, $2

Generated by \`assemble-docsync-prompts.sh\`; do not edit by hand. Hand the body below
the rule to a cold judge agent verbatim, with read-only tools. Nothing else from this
directory travels with it.

---

EOF
}

for arm in red green; do
  for c in case-a case-c; do
    out="$HERE/probe-prompt-docsync-$arm-${c#case-}.md"
    {
      header "$arm" "$c"
      framing "$c"
      "scanner_$arm"
      scope "$c"
      diffblock "$c"
      task
    } > "$out"
    printf '   %-34s %6s bytes\n' "$(basename "$out")" "$(wc -c < "$out" | tr -d ' ')"
  done
done
echo "DONE"
