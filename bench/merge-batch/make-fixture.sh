#!/usr/bin/env bash
# GAP-0cf5 — build the batch-landing fixture + a cold config dir.
#
#   <dir>/repo/     git repo, base `main`, no remote:
#                     main: init — features/core.txt, docs/roster.md (generated:
#                           `count: 1`, `- core`), tools/roster.sh, tools/verify.sh,
#                           CLAUDE.md + docs/techstack.md declaring both commands
#                     f1, f2, f3   one commit each off init: adds features/fN.txt
#                           and re-runs tools/roster.sh, so each bumps the roster's
#                           count line to 2 and appends `- fN`.
#                   f1 lands cleanly; once it is in, f2 and f3 conflict on
#                   docs/roster.md only — derived output the docs name.
#                   Working tree clean, on main, .bench-log empty.
#   <dir>/coldcfg/  CLAUDE_CONFIG_DIR: credentials + settings only — no
#                   device CLAUDE.md / rules / plugins / hooks reach the run.
#
# tools/roster.sh appends `roster` and tools/verify.sh appends `verify` to the
# git-ignored .bench-log, so the run's regenerate and verify calls are read
# back after it ends.
#
# Usage: bash make-fixture.sh <dir>   (outside this repo's tree; absolute path)
set -eu
FX="${1:?usage: make-fixture.sh <dir>}"
rm -rf "$FX/repo" "$FX/coldcfg"
mkdir -p "$FX/repo/tools" "$FX/repo/features" "$FX/repo/docs" "$FX/coldcfg"
R="$FX/repo"
git -C "$R" init -q -b main
git -C "$R" config user.name bench
git -C "$R" config user.email bench@example.invalid
git -C "$R" config commit.gpgsign false
git -C "$R" config core.autocrlf false
g() { git -C "$R" "$@"; }

cat > "$R/CLAUDE.md" <<'MD'
# featuredemo

Feature flags as `features/*.txt`, one file per feature. `docs/roster.md` lists them with a count.

## Commands

```bash
sh tools/roster.sh    # regenerate docs/roster.md from features/*.txt (generated file — never hand-edit)
sh tools/verify.sh    # verify: the roster matches features/
```
MD
cat > "$R/docs/techstack.md" <<'MD'
# Tech stack

Plain files and POSIX sh. No build step.

## Derived output

| Path | Written by | Source |
|---|---|---|
| `docs/roster.md` | `sh tools/roster.sh` | `features/*.txt` |

`docs/roster.md` is generated and committed. Never hand-edit it; re-run the command.

## Staged-Tree Verify

```sh
sh tools/verify.sh
```
MD
printf '.bench-log\n' > "$R/.gitignore"
cat > "$R/tools/roster.sh" <<'SH'
#!/bin/sh
# Regenerate docs/roster.md from features/*.txt.
echo roster >> .bench-log
n=0; list=""
for f in features/*.txt; do n=$((n+1)); list="$list- $(basename "$f" .txt)
"; done
{
  printf '# Feature roster\n\n<!-- generated by sh tools/roster.sh from features/*.txt; do not hand-edit -->\n\n'
  printf 'count: %s\n\n' "$n"
  printf '%s' "$list"
} > docs/roster.md
SH
cat > "$R/tools/verify.sh" <<'SH'
#!/bin/sh
# Verify: docs/roster.md lists every feature file, with the right count.
echo verify >> .bench-log
rc=0
n=$(ls features/*.txt | wc -l | tr -d ' ')
grep -qx "count: $n" docs/roster.md || { echo "roster: count line is not 'count: $n'"; rc=1; }
for f in features/*.txt; do
  b=$(basename "$f" .txt)
  grep -qx -- "- $b" docs/roster.md || { echo "roster: missing '- $b'"; rc=1; }
done
grep -q '^[<=>]\{7\}' docs/roster.md && { echo "roster: conflict markers"; rc=1; }
[ $rc -eq 0 ] && echo "verify OK" || echo "verify FAILED"
exit $rc
SH
printf 'core\n' > "$R/features/core.txt"
(cd "$R" && sh tools/roster.sh)
g add -A && g commit -qm "init"

for b in f1 f2 f3; do
  g checkout -q -b "$b" main
  printf '%s\n' "$b" > "$R/features/$b.txt"
  (cd "$R" && sh tools/roster.sh)
  g add -A && g commit -qm "feat($b): add $b"
  g checkout -q main
done
: > "$R/.bench-log"
(cd "$R" && sh tools/verify.sh >/dev/null) || { echo "fixture verify red" >&2; exit 1; }
: > "$R/.bench-log"
[ -z "$(g status --porcelain)" ] || { echo "fixture dirty" >&2; exit 1; }

[ -f "$HOME/.claude/.credentials.json" ] && cp "$HOME/.claude/.credentials.json" "$FX/coldcfg/"
cat > "$FX/coldcfg/settings.json" <<'JSON'
{
  "hooks": {},
  "enabledPlugins": {},
  "includeCoAuthoredBy": false,
  "permissions": {
    "defaultMode": "acceptEdits",
    "allow": [
      "Bash(git:*)", "Bash(sh:*)", "Bash(pwd)", "Bash(ls:*)", "Bash(echo:*)", "Bash(cat:*)", "Bash(test:*)",
      "PowerShell(git:*)", "PowerShell(Get-Location)"
    ]
  }
}
JSON
g log --oneline --graph --all
echo "fixture at $R; cold config at $FX/coldcfg"
